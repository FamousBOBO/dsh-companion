import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const ops=path.dirname(fileURLToPath(import.meta.url));
import { suite } from './paths.mjs';
const config=JSON.parse(fs.readFileSync(path.join(suite,'config/suite.json')));
const data=path.join(suite,'data');
const log=path.join(data,'logs/production-host.log');
const record=path.join(data,'tmp/production.json');
const cli=path.join(config.dsh.moduleRoot,'@deepseek-ai/dsh-desktop-host/lib/cli.js');
const env={...process.env,DSH_HOME:path.join(data,'home'),DSH_PROFILE:'companion',DSH_COMPANION_SUITE_ROOT:suite,DSH_COMPANION_DATA_DIR:data,DSH_COMPANION_MODULE_ROOT:config.dsh.moduleRoot,DSH_PERMISSION_MODE:'workspace-write',TEMP:path.join(data,'tmp'),TMP:path.join(data,'tmp'),TMPDIR:path.join(data,'tmp')};
delete env.ELECTRON_RUN_AS_NODE;
fs.mkdirSync(path.dirname(record),{recursive:true});
const fd=fs.openSync(log,'a');
fs.writeSync(fd,`\nProduction Node host started ${new Date().toISOString()}\n`);
const child=spawn(process.execPath,['--expose-internals',cli,'--profile','companion','--patch',path.join(suite,'config/profile/companion.patch.yml'),'--port','3100','--host','127.0.0.1','--no-open'],{cwd:path.join(data,'workspace'),env,windowsHide:true,stdio:['ignore',fd,fd]});
fs.closeSync(fd);
fs.writeFileSync(record,JSON.stringify({pid:process.pid,hostPid:child.pid,node:process.execPath,startedAt:new Date().toISOString(),log,port:3100},null,2));
child.on('error',err=>{fs.appendFileSync(log,`Host spawn failed: ${err.message}\n`);process.exitCode=1;});
child.on('exit',code=>{fs.appendFileSync(log,`Host exited: ${code}\n`);process.exit(code??1);});
