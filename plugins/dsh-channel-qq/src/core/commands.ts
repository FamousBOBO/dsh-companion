/** 群聊斜杠命令的判定（纯函数）：2026-11-01 使用者要求「群聊里所有 `/` 命令都关闭」。
 *
 * 为什么单独放 `core/`：这是一条**按字面就能判**的规则（不看配置、不看身份、不看房间开关），
 * 所以它该是纯函数、可单独测——而不是散在入站分发里的一段 `if`。
 *
 * 口径（刻意从简）：
 *   - 只看**消息正文**（`plainText`/`raw_message` 的文本段），不看昵称、不看引用、不看卡片标题；
 *   - 以 `/` 或 `／`（全角）打头、前面允许空白，就算命令；
 *   - **群聊里不区分是哪条命令**：一律当"这一条不处理"，既不执行、也不进旁听、也不交给模型。
 *     私聊不受影响（管理员命令 `/换血`、访问门控审批等仍然只在私聊可用）。
 */
export function isSlashCommandText(text: string): boolean {
  const head = text.trimStart()
  return head.startsWith('/') || head.startsWith('／')
}
