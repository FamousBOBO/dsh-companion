// Entry rendering
// ---------------------------------------------------------------------------

function sanitizeInline(value, maxChars) {
  const text = redactSecrets(String(value ?? '')).replace(/\s+/g, ' ').trim();
  return truncate(text, maxChars);
}

function entryBody(record) {
  const value = sanitizeInline(record.value, MAX_BODY_CHARS);
  const content = sanitizeInline(record.content, MAX_CONTENT_CHARS);
  if (!value && !content) return '（无正文）';
  if (!content) return value;
  if (!value) return content;
  return `${value}（${content}）`;
}

/**
 * A memory value is data, never page structure. If a value contained a literal
 * control marker (`<!-- manual:end -->`, `<!-- generated:end -->`, ...) the next
 * compile would parse it as the beginning/end of a region and could capture or
 * destroy the user's manual notes. Every piece of generated text therefore
 * breaks the comment opener: `<!--` becomes `<\!--`. Markdown swallows the
 * backslash before `!`, so a reader still sees `<!--` on screen.
 */
function escapeControlMarkers(value) {
  return String(value ?? '').replaceAll('<!--', '<\\!--');
}

function entryTime(record) {
  const raw = record.occurredAt || record.validFrom || record.updatedAt || record.createdAt || '';
  return parseTime(raw) ?? '时间未知';
}

function evidenceCount(evidenceById, id) {
  if (!evidenceById) return 0;
  const rows = typeof evidenceById.get === 'function' ? evidenceById.get(id) : evidenceById[id];
  return Array.isArray(rows) ? rows.length : 0;
}

function renderEntry(record, evidenceById, hidden) {
  const meta = [`来源 ${escapeControlMarkers(record.sourceKind || 'unknown')}`];
  meta.push(realityLabel(record));
  meta.push(entryTime(record));
  if (record.worldId) meta.push(`world:${escapeControlMarkers(record.worldId)}`);
  if (record.scope && record.scope !== 'user_global' && record.scope !== 'user_persona') {
    meta.push(scopeLabel(record.scope));
  }
  const evidence = evidenceCount(evidenceById, record.id);
  if (evidence > 0) meta.push(`证据 ${evidence} 条`);
  const body = hidden ? HIDDEN_BODY : entryBody(record);
  // Escape the whole line: id, meta and body are all database material.
  return escapeControlMarkers(`- [mem:${record.id}] ${meta.join(' · ')} — ${body}`);
}

function groupByKind(records) {
  // Records arrive in importance order, so kinds are interleaved; group them but
  // keep the importance order inside every group.
  const buckets = new Map();
  for (const record of records) {
    const kind = String(record.kind ?? '');
    if (!buckets.has(kind)) buckets.set(kind, []);
    buckets.get(kind).push(record);
  }
  const ordered = [...KIND_ORDER.filter(kind => buckets.has(kind)), ...[...buckets.keys()].filter(kind => !KIND_ORDER.includes(kind)).sort(compareText)];
  return ordered.map(kind => ({ kind, records: buckets.get(kind) }));
}

function partitionSection(heading, records, evidenceById) {
  const lines = [heading, ''];
  const visible = records.filter(record => record.mentionPolicy !== 'avoid_unless_asked');
  const hidden = records.filter(record => record.mentionPolicy === 'avoid_unless_asked');
  for (const group of groupByKind(visible)) {
    lines.push(`### ${kindLabel(group.kind)}（${group.records.length} 条）`, '');
    for (const record of group.records) lines.push(renderEntry(record, evidenceById, false));
    lines.push('');
  }
  if (hidden.length) {
    lines.push(`### 暂不展开（${hidden.length} 条）`, '');
    for (const record of hidden) lines.push(renderEntry(record, evidenceById, true));
    lines.push('');
  }
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  return lines.join('\n');
}

function partitionRecords(selected) {
  const reality = [];
  const fiction = [];
  for (const record of selected) (isFiction(record) ? fiction : reality).push(record);
  return { reality, fiction };
}

function fictionHeading(fiction) {
  const worldIds = [...new Set(fiction.map(record => record.worldId).filter(Boolean))].sort()
    .map(worldId => escapeControlMarkers(worldId));
  if (worldIds.length) return `## 剧情世界 · ${worldIds.join(' / ')}（仅在该剧情内有效，不作为现实事实）`;
  return '## 剧情设定（非现实，不作为现实事实）';
}

// ---------------------------------------------------------------------------
// Page rendering
// ---------------------------------------------------------------------------

function byteLength(text) {
  return Buffer.byteLength(String(text ?? ''), 'utf8');
}

function clampEntryLimit(value, fallback) {
  const number = Number(value);
  if (!Number.isFinite(number)) return fallback;
  const floored = Math.floor(number);
  if (floored < 1) return fallback;
  return Math.min(floored, HARD_ENTRY_LIMIT);
}

function clampByteLimit(value, fallback) {
  const number = Number(value);
  if (!Number.isFinite(number)) return fallback;
  const floored = Math.floor(number);
  if (floored < 512) return fallback;
  return Math.min(floored, HARD_PAGE_BYTES);
}

function clampSortVersion(value, fallback) {
  const number = Number(value);
  if (!Number.isFinite(number)) return fallback;
  const floored = Math.floor(number);
  if (floored < 1) return fallback;
  return Math.min(floored, 1_000_000);
}

/** Generated region for one topic page and the entries that survived the caps. */
function buildPageMarkdown({ topic, entries, total, evidenceById, sourceRevision }) {
  const { reality, fiction } = partitionRecords(entries);
  const hiddenCount = entries.filter(record => record.mentionPolicy === 'avoid_unless_asked').length;
  const omitted = Math.max(0, total - entries.length);
  const blocks = [];
  blocks.push(`${GENERATED_BEGIN} ${topic.id} rev-${sourceRevision.toString(16)} -->`);
  blocks.push(`# ${topic.topic}`);

  const notes = [];
  notes.push([
    topic.description,
    scopeLabel(topic.scope),
    `数据版本 ${sourceRevision}（rev-${sourceRevision.toString(16)}）`,
    `已确认条目 ${total} 条`,
  ].join(' · '));
  if (hiddenCount) notes.push(`其中 ${hiddenCount} 条只保留占位，正文不写入本页。`);
  notes.push('本区由 companion-memory 自动编译，每次重编译整体替换；个人笔记请写在下方 manual 区。');
  if (reality.length && fiction.length) {
    notes.push('本页同时包含现实与剧情内容：剧情部分单独分区并标注，不作为现实事实。');
  }
  if (omitted) {
    notes.push(`仅展示最重要的 ${entries.length} 条（共 ${total} 条）。完整历史请用 companion_recall 检索，或查看数据库原始记录。`);
  }
  blocks.push(notes.map(note => `> ${note}`).join('\n'));

  if (!entries.length) {
    blocks.push(total
      ? '_（条目超出本页容量上限，无法展示；请用 companion_recall 检索。）_'
      : EMPTY_PAGE_BODY);
  }
  if (reality.length) blocks.push(partitionSection('## 现实', reality, evidenceById));
  if (fiction.length) blocks.push(partitionSection(fictionHeading(fiction), fiction, evidenceById));
  blocks.push(GENERATED_END);

  return { markdown: blocks.join('\n\n'), hiddenCount };
}

/**
 * Render the generated region of one topic page.
 *
 * Two independent caps keep a page readable: at most `maxEntriesPerTopic`
 * entries, and at most `maxPageBytes` bytes of generated markdown. Both are part
 * of the returned `sourceRevision`, so the same data plus the same caps always
 * produces the same bytes.
 *
 * -> { markdown, sourceRevision, entryCount, hiddenCount, totalCount, omittedCount, truncated, overflow }
 */
export function renderPage({
  topic,
  records = [],
  evidenceById = null,
  viewer = null,
  now,
  maxEntriesPerTopic = DEFAULT_MAX_ENTRIES_PER_PAGE,
  maxPageBytes = DEFAULT_MAX_PAGE_BYTES,
  sortVersion = WIKI_SORT_VERSION,
} = {}) {
  const descriptor = normalizeTopic(topic);
  const nowMs = toMillis(now);
  const entryLimit = clampEntryLimit(maxEntriesPerTopic, DEFAULT_MAX_ENTRIES_PER_PAGE);
  const byteLimit = clampByteLimit(maxPageBytes, DEFAULT_MAX_PAGE_BYTES);
  const ruleVersion = clampSortVersion(sortVersion, WIKI_SORT_VERSION);
  const available = selectRecords(descriptor, records, viewer, nowMs);
  const total = available.length;
  const capped = available.slice(0, entryLimit);
  const sourceRevision = revisionOf(descriptor, available, evidenceById, {
    maxEntriesPerTopic: entryLimit,
    maxPageBytes: byteLimit,
    sortVersion: ruleVersion,
  });

  let shown = capped.length;
  let built = buildPageMarkdown({
    topic: descriptor,
    entries: capped,
    total,
    evidenceById,
    sourceRevision,
  });
  let overflow = false;

  if (byteLength(built.markdown) > byteLimit) {
    // Page size grows monotonically with the number of entries, so binary search
    // for the longest prefix that still fits the byte budget.
    let low = 0;
    let high = capped.length;
    while (low < high) {
      const middle = Math.ceil((low + high) / 2);
      const candidate = buildPageMarkdown({
        topic: descriptor,
        entries: capped.slice(0, middle),
        total,
        evidenceById,
        sourceRevision,
      });
      if (byteLength(candidate.markdown) <= byteLimit) low = middle;
      else high = middle - 1;
    }
    shown = low;
    built = buildPageMarkdown({
      topic: descriptor,
      entries: capped.slice(0, shown),
      total,
      evidenceById,
      sourceRevision,
    });
    overflow = byteLength(built.markdown) > byteLimit;
  }

  return {
    markdown: built.markdown,
    sourceRevision,
    entryCount: shown,
    hiddenCount: built.hiddenCount,
    totalCount: total,
    omittedCount: Math.max(0, total - shown),
    truncated: shown < total,
    overflow,
  };
}

function indexRevisionOf(items) {
  const signature = items.map(item => [item.pageId, item.path, item.scope, item.topic, item.sourceRevision ?? '', item.entryCount ?? ''].join('\u0001')).join('\u0002');
  return parseInt(contentHash(`wiki-index\u0000${signature}`).slice(0, 8), 16);
}

function normalizeIndexItem(page) {
  const identifier = page?.pageId ?? page?.id ?? '';
  const known = topicById(identifier);
  return {
    pageId: String(identifier || known?.id || ''),
    path: String(page?.path ?? known?.path ?? ''),
    scope: String(page?.scope ?? known?.scope ?? 'user_global'),
    topic: String(page?.topic ?? known?.topic ?? '主题页'),
    description: String(page?.description ?? known?.description ?? ''),
    sourceRevision: Number.isFinite(page?.sourceRevision) ? page.sourceRevision : null,
    entryCount: Number.isFinite(page?.entryCount) ? page.entryCount : null,
  };
}

function buildIndexMarkdown(items, { withDescription, revision }) {
  const lines = [
    `${GENERATED_BEGIN} ${WIKI_INDEX_ID} rev-${revision.toString(16)} -->`,
    '',
    '# 记忆主题索引',
    '',
  ];
  for (const item of items) {
    const label = withDescription && item.description ? `${item.topic}（${item.description}）` : item.topic;
    lines.push(`- ${label} · ${scopeLabel(item.scope)} · ${item.pageId} · ${item.path}`);
  }
  lines.push('', GENERATED_END);
  return lines.join('\n');
}

/** Source revision recorded for index.md; matches the rev- marker it renders. */
export function indexRevision({ pages = [] } = {}) {
  return indexRevisionOf(pages.map(normalizeIndexItem));
}

/**
 * Render the generated region of index.md. Short by construction: the longest
 * variant that fits the budget wins, descriptions are dropped first.
 */
export function renderIndex({ pages = [], maxChars = INDEX_GENERATED_MAX_CHARS } = {}) {
  const items = (Array.isArray(pages) ? pages : []).map(normalizeIndexItem);
  const revision = indexRevisionOf(items);
  let shortest = '';
  for (const withDescription of [true, false]) {
    const markdown = buildIndexMarkdown(items, { withDescription, revision });
    shortest = markdown;
    if (markdown.length <= maxChars) return markdown;
  }
  return shortest;
}

