// Wiki topic compiler for the companion memory engine.
//
// The database is the source of truth; a wiki page is only a derived, human
// readable view of it. This module therefore never invents content: a record
// reaches a page only after it passed the shared status/scope gates from
// lib/policy.mjs, and every rendered entry keeps its memory id, source kind,
// reality label and timestamp so a reader can trace it back.
//
// Page layout (each topic page and index.md):
//
//   <!-- generated:begin <page> rev-<hex> -->   ... owned by this module ...
//   <!-- generated:end -->
//
//   <!-- manual:begin -->                       ... owned by the user ...
//   <!-- manual:end -->
//
//   <!-- compiled: <iso time> ... -->           compile stamp, allowed to drift
//
// Recompiling replaces the generated region only. Everything between the manual
// markers is copied byte for byte from the page on disk, including text the
// user typed by hand. The compile stamp lives outside both regions so that
// "same data in -> same generated bytes out" holds even when `now` moves; pass
// a fixed `now` when you need the whole file to be byte identical.
//
// A topic page is a digest, not a mirror of the database: entries are capped per
// page both by count (MAX_ENTRIES_PER_PAGE) and by bytes (MAX_PAGE_BYTES), the
// kept entries are the most valuable ones, and the page states plainly that it
// dropped content. Without those caps a real library (hundreds of imported
// conversation summaries) turns one page into a 200 KB file that neither a human
// nor a model can read in one go.
//
// Ranking (WIKI_SORT_VERSION 2) is kind tier first, then importance: structured
// event/commitment/relationship rows outrank profile/fact rows, which outrank
// derived conversation summaries. Importance alone would let imported summaries
// (default importance 0.9) take every slot on the shared-events page.

