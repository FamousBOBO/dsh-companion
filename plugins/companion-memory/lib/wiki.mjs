// Database integration (degradable)
// ---------------------------------------------------------------------------

function listVisibleRecords(db, viewer, warnings) {
  if (!viewer) return [];
  if (!db || typeof db.listMemories !== 'function') {
    warnings.push('db.listMemories 不可用，本次编译按空库处理。');
    return [];
  }
  const filter = { status: 'confirmed', userId: viewer.userId, personaId: viewer.personaId };
  const pageSize = 500;
  const seen = new Map();
  for (let page = 0; page < 40; page += 1) {
    const offset = page * pageSize;
    let batch;
    try {
      batch = db.listMemories({ ...filter, limit: pageSize, offset });
    } catch (error) {
      warnings.push(`读取记忆失败：${errorMessage(error)}`);
      break;
    }
    if (!Array.isArray(batch) || !batch.length) break;
    let fresh = 0;
    for (const record of batch) {
      if (!record || typeof record.id !== 'string' || !record.id) continue;
      if (seen.has(record.id)) continue;
      seen.set(record.id, record);
      fresh += 1;
    }
    if (batch.length < pageSize || fresh === 0) break;
  }
  return [...seen.values()];
}

function collectEvidence(db, records) {
  const map = new Map();
  if (!db || typeof db.evidenceFor !== 'function') return map;
  let budget = EVIDENCE_LOOKUP_BUDGET;
  for (const record of records) {
    if (budget <= 0) break;
    if (record.mentionPolicy === 'avoid_unless_asked') continue;
    budget -= 1;
    try {
      const rows = db.evidenceFor(record.id);
      if (Array.isArray(rows) && rows.length) map.set(record.id, rows);
    } catch {
      // Evidence is decoration on the page; never fail the compile for it.
    }
  }
  return map;
}

function registerPage(db, payload, warnings) {
  if (!db || typeof db.upsertWikiPage !== 'function') {
    warnings.push(`db.upsertWikiPage 不可用，${payload.path} 只写入文件、未登记数据库。`);
    return false;
  }
  try {
    db.upsertWikiPage(payload);
    return true;
  } catch (error) {
    // Tolerate a stricter schema that rejects the navigation scope.
    if (payload.scope === 'system') {
      try {
        db.upsertWikiPage({ ...payload, scope: 'user_global' });
        return true;
      } catch {
        // fall through to the warning below
      }
    }
    warnings.push(`登记 ${payload.path} 失败：${errorMessage(error)}`);
    return false;
  }
}

function validViewer(viewer, warnings) {
  if (!viewer || !viewer.userId || !viewer.personaId) {
    warnings.push('缺少 viewer（userId/personaId），本次编译不读取任何记忆。');
    return null;
  }
  return {
    userId: String(viewer.userId),
    personaId: String(viewer.personaId),
    worldId: String(viewer.worldId ?? ''),
  };
}

