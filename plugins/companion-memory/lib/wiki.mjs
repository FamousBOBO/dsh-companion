/**
 * Compile every topic page plus index.md below `dir`.
 * -> { pages, index, indexMarkdown, warnings }
 *
 * `maxEntriesPerTopic` / `maxPageBytes` override the digest caps (MAX_ENTRIES_PER_PAGE
 * / MAX_PAGE_BYTES); they participate in `sourceRevision`, so changing them
 * republishes the pages instead of silently pretending nothing happened.
 *
 * Database problems degrade to file-only output with warnings; this function
 * never throws for a missing/partial db (CONTRACT.md §13).
 */
export async function compileWiki({
  dir,
  db = null,
  viewer = null,
  now,
  maxEntriesPerTopic = DEFAULT_MAX_ENTRIES_PER_PAGE,
  maxPageBytes = DEFAULT_MAX_PAGE_BYTES,
  sortVersion = WIKI_SORT_VERSION,
} = {}) {
  const root = resolveRoot(dir);
  fs.mkdirSync(root, { recursive: true });
  const nowMs = toMillis(now);
  const warnings = [];
  const effectiveViewer = validViewer(viewer, warnings);
  const records = listVisibleRecords(db, effectiveViewer, warnings);
  const evidenceById = collectEvidence(db, records);

  const pages = [];
  for (const topic of WIKI_TOPICS) {
    const rendered = renderPage({
      topic,
      records,
      evidenceById,
      viewer: effectiveViewer,
      now: nowMs,
      maxEntriesPerTopic,
      maxPageBytes,
      sortVersion,
    });
    if (rendered.overflow) {
      warnings.push(`${topic.path} 只保留页头也超过 ${maxPageBytes} 字节上限，请检查页面模板或上限配置。`);
    }
    const file = path.join(root, ...topic.path.split('/'));
    const previous = readIfExists(file);
    const layout = planPageLayout(previous);
    if (!layout.ok) {
      // Never guess: a page whose control markers are ambiguous keeps its bytes
      // exactly as they are, and the caller decides how to repair it.
      warnings.push(`manual-region-invalid: ${layout.reason}（${topic.path} 保持原样，未重写）`);
      pages.push({
        pageId: topic.id,
        path: topic.path,
        scope: topic.scope,
        topic: topic.topic,
        sourceRevision: rendered.sourceRevision,
        entryCount: rendered.entryCount,
        hiddenCount: rendered.hiddenCount,
        totalCount: rendered.totalCount,
        truncated: rendered.truncated,
        bytes: byteLength(previous ?? ''),
        changed: false,
        invalid: true,
      });
      continue;
    }
    const manual = manualRegionFrom(previous, layout);
    const content = assemblePage({
      generated: rendered.markdown,
      manual,
      footer: compiledFooter({
        pageId: topic.id,
        sourceRevision: rendered.sourceRevision,
        worldId: effectiveViewer?.worldId ?? '',
        now: nowMs,
      }),
    });
    const changed = writePage(file, content, warnings, previous);
    registerPage(db, {
      pageId: topic.id,
      scope: topic.scope,
      topic: topic.topic,
      path: topic.path,
      sourceRevision: rendered.sourceRevision,
      contentHash: contentHash(content),
      status: 'compiled',
      notes: `条目 ${rendered.entryCount} 条（占位 ${rendered.hiddenCount} 条，共 ${rendered.totalCount} 条）`,
    }, warnings);
    pages.push({
      pageId: topic.id,
      path: topic.path,
      scope: topic.scope,
      topic: topic.topic,
      sourceRevision: rendered.sourceRevision,
      entryCount: rendered.entryCount,
      hiddenCount: rendered.hiddenCount,
      totalCount: rendered.totalCount,
      truncated: rendered.truncated,
      bytes: byteLength(content),
      changed,
      invalid: false,
    });
  }

  const indexFile = path.join(root, ...WIKI_INDEX_PATH.split('/'));
  const indexPrevious = readIfExists(indexFile);
  const indexLayout = planPageLayout(indexPrevious);
  if (!indexLayout.ok) {
    warnings.push(`manual-region-invalid: ${indexLayout.reason}（${WIKI_INDEX_PATH} 保持原样，未重写）`);
    const indexItems = WIKI_TOPICS.map(topic => ({ ...topic, ...(pages.find(page => page.pageId === topic.id) ?? {}) }));
    const indexPage = {
      pageId: WIKI_INDEX_ID,
      path: WIKI_INDEX_PATH,
      scope: 'system',
      topic: '记忆主题索引',
      sourceRevision: indexRevision({ pages: indexItems }),
      entryCount: indexItems.length,
      bytes: byteLength(indexPrevious ?? ''),
      changed: false,
      invalid: true,
    };
    return { pages, index: { ...indexPage, markdown: indexPrevious ?? '' }, indexMarkdown: '', warnings };
  }
  const indexManual = manualRegionFrom(indexPrevious, indexLayout);
  const indexBudget = Math.max(120, WIKI_INDEX_MAX_CHARS - indexManual.length - 4);
  const indexItems = WIKI_TOPICS.map(topic => {
    const result = pages.find(page => page.pageId === topic.id);
    return { ...topic, ...(result ?? {}) };
  });
  const indexMarkdown = renderIndex({ pages: indexItems, maxChars: indexBudget });
  const indexContent = assemblePage({ generated: indexMarkdown, manual: indexManual });
  const indexChanged = writePage(indexFile, indexContent, warnings, indexPrevious);
  if (indexContent.length > WIKI_INDEX_MAX_CHARS) {
    warnings.push(`index.md 超过 ${WIKI_INDEX_MAX_CHARS} 字（当前 ${indexContent.length} 字），请精简人工区。`);
  }
  const indexPage = {
    pageId: WIKI_INDEX_ID,
    path: WIKI_INDEX_PATH,
    scope: 'system',
    topic: '记忆主题索引',
    sourceRevision: indexRevision({ pages: indexItems }),
    entryCount: indexItems.length,
    bytes: byteLength(indexContent),
    changed: indexChanged,
    invalid: false,
  };
  registerPage(db, {
    pageId: indexPage.pageId,
    scope: indexPage.scope,
    topic: indexPage.topic,
    path: indexPage.path,
    sourceRevision: indexPage.sourceRevision,
    contentHash: contentHash(indexContent),
    status: 'compiled',
    notes: `主题 ${indexPage.entryCount} 个`,
  }, warnings);

  return { pages, index: { ...indexPage, markdown: indexContent }, indexMarkdown, warnings };
}

