function isWithin(root, target) {
  const relative = path.relative(root, target);
  if (relative === '') return true;
  if (path.isAbsolute(relative)) return false;
  return !relative.split(path.sep).includes('..');
}

/** Real path of a file that may not exist yet (resolves the nearest ancestor). */
function realPathOf(target) {
  const missing = [];
  let current = path.resolve(target);
  for (let depth = 0; depth < 64; depth += 1) {
    try {
      const real = fs.realpathSync.native(current);
      return missing.length ? path.join(real, ...missing.reverse()) : real;
    } catch (error) {
      if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') throw error;
      const parent = path.dirname(current);
      if (parent === current) return path.resolve(target);
      missing.push(path.basename(current));
      current = parent;
    }
  }
  return path.resolve(target);
}

function normalizeRelativePath(topicId) {
  if (typeof topicId !== 'string') throw new TypeError('readPage 需要一个页面标识（topicId）。');
  const raw = topicId.trim();
  if (!raw) throw new Error('无效的 Wiki 页面标识：不能为空。');
  if (raw.includes('\u0000')) throw new Error('无效的 Wiki 页面标识：不能包含空字符。');
  const unified = raw.replaceAll('\\', '/');
  if (unified.startsWith('/') || unified.startsWith('//') || /^[a-zA-Z]:/.test(unified)) {
    throw new Error('Wiki 页面标识不允许使用绝对路径。');
  }
  const segments = unified.split('/');
  for (const segment of segments) {
    if (!segment || segment === '.') throw new Error(`无效的 Wiki 页面标识：${topicId}`);
    if (segment === '..') throw new Error('Wiki 页面标识不允许越出 Wiki 目录。');
    if (segment.includes(':')) throw new Error('Wiki 页面标识不允许包含驱动器或数据流分隔符。');
  }
  const known = topicById(unified);
  if (known) return { relative: known.path, knownId: known.id };
  if (unified === WIKI_INDEX_ID || unified === WIKI_INDEX_PATH) {
    return { relative: WIKI_INDEX_PATH, knownId: WIKI_INDEX_ID };
  }
  const last = segments[segments.length - 1];
  return { relative: /\.[a-zA-Z0-9]+$/.test(last) ? unified : `${unified}.md`, knownId: null };
}

function assertInside(root, file) {
  const lexicalRoot = path.resolve(root);
  const lexicalFile = path.resolve(file);
  if (!isWithin(lexicalRoot, lexicalFile)) throw new Error('Wiki 页面路径越界，已拒绝。');
  if (!isWithin(realPathOf(lexicalRoot), realPathOf(lexicalFile))) {
    throw new Error('Wiki 页面路径越界，已拒绝（符号链接逃逸）。');
  }
}

/**
 * Read one page by topic id, topic path or relative path inside `dir`.
 * -> { topicId, path, markdown, exists }; throws on any path escape.
 */
export function readPage({ dir, topicId } = {}) {
  const root = resolveRoot(dir);
  const { relative, knownId } = normalizeRelativePath(topicId);
  const file = path.join(root, ...relative.split('/'));
  assertInside(root, file);
  const exists = fileExists(file);
  const markdown = exists ? fs.readFileSync(file, 'utf8') : '';
  return { topicId: knownId ?? relative, path: relative, markdown, exists };
}
