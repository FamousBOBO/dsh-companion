/** Canonical descriptor for a topic id (or path); null when unknown. */
export function topicById(topicId) {
  const needle = String(topicId ?? '').trim();
  if (!needle) return null;
  return WIKI_TOPICS.find(item => item.id === needle || item.path === needle) ?? null;
}

function normalizeTopic(topic) {
  if (typeof topic === 'string') {
    const found = topicById(topic);
    if (!found) throw new Error(`未知的 Wiki 主题：${topic}`);
    return found;
  }
  if (!topic || typeof topic !== 'object' || !topic.id) {
    throw new TypeError('renderPage 需要一个主题描述（topic.id）。');
  }
  const known = topicById(topic.id);
  if (known) return { ...known, ...topic, includeWorld: topic.includeWorld ?? known.includeWorld };
  return {
    description: '主题页',
    includeWorld: true,
    ...topic,
  };
}

function topicForRecord(record) {
  const kind = String(record.kind ?? '');
  if (!Object.hasOwn(KIND_TOPIC, kind)) return null;
  const target = KIND_TOPIC[kind];
  if (!target) return null;
  if (kind === 'fact' || kind === 'note') {
    return record.scope === 'user_persona' ? 'relationship-march7' : target;
  }
  return target;
}

function kindLabel(kind) {
  return KIND_LABELS[kind] ?? '其他';
}

function kindPriority(kind) {
  return KIND_PRIORITY[kind] ?? 1;
}

/** Fiction rows are rendered in their own labelled partition, never as reality. */
function isFiction(record) {
  return Boolean(record.worldId) || record.scope === 'roleplay_world' || record.realityLevel === 'roleplay_fiction';
}

// ---------------------------------------------------------------------------
// Record selection
// ---------------------------------------------------------------------------

function toMillis(value) {
  if (value == null) return Date.now();
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  const parsed = Date.parse(String(value));
  return Number.isFinite(parsed) ? parsed : Date.now();
}

function compareText(left, right) {
  // Plain code-unit comparison: localeCompare would make the page depend on the
  // host locale, and a stable page must produce the same bytes everywhere.
  if (left === right) return 0;
  return left < right ? -1 : 1;
}

/**
 * Digest order (WIKI_SORT_VERSION 2): kind tier first, then importance, then
 * newest first, then id for stability. Truncation keeps the head of this list,
 * so derived conversation summaries can never push structured events off their
 * own page, no matter what importance an importer assigned to them.
 */
function sortRecords(records) {
  return [...records].sort((left, right) => {
    const priorityDelta = kindPriority(left.kind) - kindPriority(right.kind);
    if (priorityDelta) return priorityDelta;
    const importanceDelta = (Number(right.importance) || 0) - (Number(left.importance) || 0);
    if (importanceDelta) return importanceDelta;
    const leftTime = String(left.occurredAt ?? left.updatedAt ?? '');
    const rightTime = String(right.occurredAt ?? right.updatedAt ?? '');
    const timeDelta = compareText(rightTime, leftTime);
    if (timeDelta) return timeDelta;
    return compareText(String(left.id), String(right.id));
  });
}

/**
 * Apply the read gates: confirmed + active + visible to the viewer + belongs to
 * this topic. `viewer` is optional here only so pure rendering can be tested;
 * compileWiki always supplies a validated viewer.
 */
function selectRecords(topic, records, viewer, nowMs) {
  const list = Array.isArray(records) ? records : [];
  const seen = new Set();
  const selected = [];
  for (const record of list) {
    if (!record || typeof record.id !== 'string' || !record.id) continue;
    if (seen.has(record.id)) continue;
    if (record.status !== 'confirmed') continue;
    if (!isActive(record, nowMs)) continue;
    // Character self state and transient session state are not stable facts.
    if (record.scope === 'persona_self' || record.scope === 'session_recent') continue;
    if (viewer && !scopeMatches(record, viewer)) continue;
    if (topicForRecord(record) !== topic.id) continue;
    if (isFiction(record) && !topic.includeWorld) continue;
    seen.add(record.id);
    selected.push(record);
  }
  return sortRecords(selected);
}

function revisionOf(topic, selected, evidenceById, limits) {
  const signature = selected.map(record => [
    record.id,
    record.revision ?? 0,
    record.updatedAt ?? '',
    record.kind ?? '',
    record.scope ?? '',
    record.worldId ?? '',
    record.mentionPolicy ?? '',
    record.realityLevel ?? '',
    record.sourceKind ?? '',
    record.value ?? '',
    record.content ?? '',
    record.occurredAt ?? '',
    record.validFrom ?? '',
    record.validTo ?? '',
    record.createdAt ?? '',
    evidenceCount(evidenceById, record.id),
  ].join('\u0001')).join('\u0002');
  // The caps and the ranking rule version are part of the signature: changing
  // them changes what the page shows, so the revision must change too.
  // Truncation is a pure function of the full selection plus the caps, so
  // "same data + same config -> same bytes" still holds.
  const budget = `${limits.maxEntriesPerTopic}\u0000${limits.maxPageBytes}\u0000${limits.sortVersion}`;
  return parseInt(contentHash(`wiki\u0000${topic.id}\u0000${budget}\u0000${signature}`).slice(0, 8), 16);
}

