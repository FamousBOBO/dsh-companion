function stripStrayMarkers(text) {
  return String(text ?? '')
    .split('\n')
    .filter(line => !/^<!--\s*(?:generated|manual|compiled):/.test(line.trim()))
    .join('\n');
}

const CONTROL_MARKER_PATTERN = /<!--([\s\S]*?)-->/g;

function classifyControlMarker(inner) {
  const text = String(inner ?? '').trim();
  if (/^generated:begin(?:\s[\s\S]*)?$/.test(text)) return 'generated:begin';
  if (text === 'generated:end') return 'generated:end';
  if (text === 'manual:begin') return 'manual:begin';
  if (text === 'manual:end') return 'manual:end';
  return null;
}

/** Positions of the four wiki control markers; other comments are ignored. */
function scanControlMarkers(text) {
  const markers = [];
  const source = String(text ?? '');
  CONTROL_MARKER_PATTERN.lastIndex = 0;
  let match;
  while ((match = CONTROL_MARKER_PATTERN.exec(source)) !== null) {
    const kind = classifyControlMarker(match[1]);
    if (kind) markers.push({ kind, start: match.index, end: match.index + match[0].length });
  }
  return markers;
}

function insideSpan(marker, span) {
  return Boolean(span) && marker.start >= span.start && marker.end <= span.end;
}

/**
 * Locate the generated and the manual region of a page that is already on disk.
 *
 * The generated region is found first (exactly one begin plus one end, in that
 * order); only markers outside it count as the manual region, so nothing a
 * memory value could smuggle into the generated region can ever be mistaken for
 * the user's notes. Every ambiguity — a duplicated marker, a lone begin, an
 * end before its begin — is reported as invalid and the caller must leave the
 * file completely untouched (a wrong guess here destroys handwritten notes).
 *
 * -> { ok: true, generated, manual, legacy } | { ok: false, reason }
 */
function planPageLayout(previous) {
  const text = typeof previous === 'string' ? previous : '';
  const markers = scanControlMarkers(text);
  const generatedBegins = markers.filter(marker => marker.kind === 'generated:begin');
  const generatedEnds = markers.filter(marker => marker.kind === 'generated:end');

  if (generatedBegins.length > 1 || generatedEnds.length > 1) {
    return { ok: false, reason: `生成区标记重复（generated:begin ×${generatedBegins.length}，generated:end ×${generatedEnds.length}）` };
  }
  if (generatedBegins.length !== generatedEnds.length) {
    return { ok: false, reason: '生成区标记不成对（缺少 generated:begin 或 generated:end）' };
  }
  let generated = null;
  if (generatedBegins.length === 1) {
    if (generatedBegins[0].start > generatedEnds[0].start) {
      return { ok: false, reason: '生成区标记顺序颠倒（generated:end 在 generated:begin 之前）' };
    }
    generated = { start: generatedBegins[0].start, end: generatedEnds[0].end };
  }

  // Markers inside the generated region are our own data, never page structure.
  const manualBegins = markers.filter(marker => marker.kind === 'manual:begin' && !insideSpan(marker, generated));
  const manualEnds = markers.filter(marker => marker.kind === 'manual:end' && !insideSpan(marker, generated));
  if (manualBegins.length > 1 || manualEnds.length > 1) {
    return { ok: false, reason: `人工区标记重复（manual:begin ×${manualBegins.length}，manual:end ×${manualEnds.length}）` };
  }
  if (manualBegins.length !== manualEnds.length) {
    return { ok: false, reason: '人工区标记不成对（缺少 manual:begin 或 manual:end）' };
  }
  let manual = null;
  if (manualBegins.length === 1) {
    if (manualBegins[0].start > manualEnds[0].start) {
      return { ok: false, reason: '人工区标记顺序颠倒（manual:end 在 manual:begin 之前）' };
    }
    manual = { start: manualBegins[0].start, end: manualEnds[0].end };
  }

  const outside = generated ? text.slice(0, generated.start) + text.slice(generated.end) : text;
  return { ok: true, generated, manual, legacy: stripStrayMarkers(outside).trim() };
}

function defaultManualBlock() {
  return `${MANUAL_BEGIN}\n${MANUAL_END}`;
}

/** Manual region bytes, adopting leftover handwritten content when there is none. */
function manualRegionFrom(previous, layout) {
  const text = typeof previous === 'string' ? previous : '';
  if (layout.manual) return text.slice(layout.manual.start, layout.manual.end);
  const legacy = layout.legacy ?? '';
  if (!legacy) return defaultManualBlock();
  return `${MANUAL_BEGIN}\n${legacy}\n${MANUAL_END}`;
}

function assemblePage({ generated, manual, footer = '' }) {
  const blocks = [String(generated ?? '').trimEnd(), String(manual ?? defaultManualBlock())];
  if (footer) blocks.push(footer);
  return `${blocks.join('\n\n')}\n`;
}

function compiledFooter({ pageId, sourceRevision, worldId, now }) {
  const iso = new Date(toMillis(now)).toISOString();
  return `${COMPILED_PREFIX} ${iso} · ${pageId} · source-revision ${sourceRevision} · world ${escapeControlMarkers(worldId || 'reality')} -->`;
}

// ---------------------------------------------------------------------------
// Atomic file IO
// ---------------------------------------------------------------------------

function readIfExists(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

function fileExists(file) {
  try {
    return fs.statSync(file).isFile();
  } catch {
    return false;
  }
}

/** Same-directory temp file + rename, so a crash never truncates a live page. */
function writeAtomically(file, content) {
  const directory = path.dirname(file);
  fs.mkdirSync(directory, { recursive: true });
  const temporary = path.join(directory, `.${path.basename(file)}.${randomUUID()}.tmp`);
  try {
    const handle = fs.openSync(temporary, 'wx');
    try {
      fs.writeFileSync(handle, content, 'utf8');
      fs.fsyncSync(handle);
    } finally {
      fs.closeSync(handle);
    }
    fs.renameSync(temporary, file);
  } finally {
    try {
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    } catch {
      // Best effort; a leftover temp file is harmless.
    }
  }
}

function writePage(file, content, warnings, previous) {
  const existing = previous === undefined ? readIfExists(file) : previous;
  if (existing === content) return false;
  try {
    writeAtomically(file, content);
    return true;
  } catch (error) {
    warnings.push(`写入 ${path.basename(file)} 失败：${errorMessage(error)}`);
    return false;
  }
}

function errorMessage(error) {
  return error && typeof error === 'object' && 'message' in error ? String(error.message) : String(error);
}

function resolveRoot(dir) {
  if (typeof dir !== 'string' || !dir.trim()) {
    throw new TypeError('Wiki 目录必须由调用方传入（不提供默认绝对路径）。');
  }
  return path.resolve(dir);
}

